const translations: Record<Language, Translation> = { fr, en, ar };
const listeners = new Set<() => void>();

function storedLanguage(): Language {
  const value = localStorage.getItem('immoove_language') || localStorage.getItem('bouzid_language');
  return value === 'en' || value === 'ar' ? value : 'fr';
}

export let activeLanguage: Language = storedLanguage();
export function languageText(language = activeLanguage) {
  return translations[language];
}
export function formatTranslation(value: string, variables: Record<string, string | number>) {
  return Object.entries(variables).reduce(
    (text, [key, replacement]) => text.replaceAll(`{${key}}`, String(replacement)),
    value,
  );
}
export function applyLanguage(language: Language) {
  activeLanguage = language;
  localStorage.setItem('immoove_language', language);
  localStorage.removeItem('bouzid_language');
  document.documentElement.lang = language;
  document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
  listeners.forEach((listener) => listener());
}
export function applyAuthLanguage(language: Language) {
  applyLanguage(language);
}
export function useLanguage() {
  const language = useSyncExternalStore(
    (listener) => {
      listeners.add(listener);
      return () => listeners.delete(listener);
    },
    () => activeLanguage,
    () => 'fr' as Language,
  );
  return { language, text: translations[language], setLanguage: applyLanguage };
}

applyLanguage(activeLanguage);
